// Bundles the real game code (js/levels.js, js/render.js, js/game.js) into one ES module that
// the Cloudflare Worker can import. Workers forbid eval/new Function, so instead of loading the
// scripts at runtime we paste them into a factory function at build time. Every call to
// createGame() returns a fresh, isolated game (own RNG, level state and globals).
//
// Usage: node leaderboard/scripts/build-game-factory.js [--check]
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(__dirname, '..', 'referee', 'src', 'game-factory.js');
const SCRIPTS = ['js/levels.js', 'js/render.js', 'js/game.js'];

function build() {
  const parts = SCRIPTS.map((f) => `// ----- ${f} -----\n${fs.readFileSync(path.join(ROOT, f), 'utf8')}`);
  return `// GENERATED by leaderboard/scripts/build-game-factory.js from ${SCRIPTS.join(', ')}.
// Do not edit by hand; rebuild after changing the game.
/* eslint-disable */
export function createGame() {
  const __noop = () => {};
  const __ctx = new Proxy({}, {
    get(_, p) {
      if (p === 'createLinearGradient') return () => ({ addColorStop: __noop });
      if (p === 'measureText') return () => ({ width: 0 });
      return __noop;
    },
    set() { return true; },
  });
  const __canvas = { width: 0, height: 0, getContext: () => __ctx, addEventListener: __noop };
  const __store = new Map();
  const window = { addEventListener: __noop, matchMedia: () => ({ matches: false }) };
  const document = { getElementById: (id) => (id === 'game' ? __canvas : null), body: { classList: { add: __noop } } };
  const localStorage = { getItem: (k) => (__store.has(k) ? __store.get(k) : null), setItem: (k, v) => __store.set(k, String(v)) };
  const location = { search: '' };
  const performance = { now: () => 0 };
  const requestAnimationFrame = () => 0;
  const SFX = new Proxy({ muted: false }, { get: (t, p) => (p in t ? t[p] : __noop) });
  const Music = { play: __noop, hold: __noop, toggle: () => true, enabled: true, track: null };

${parts.join('\n')}

  return window.SysCommander;
}
`;
}

const code = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== code) { console.error('game-factory.js is out of date: run node leaderboard/scripts/build-game-factory.js'); process.exit(1); }
  console.log('game-factory.js is up to date');
} else {
  fs.writeFileSync(OUT, code);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${(code.length / 1024).toFixed(0)} KB)`);
}
